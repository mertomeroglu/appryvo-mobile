/** Non-React callers (socket handlers, push toasts) -- mirrors appLocale's translateSync. */
export function questionTextSync(key: QuestionTextKey, vars?: Record<string, string | number>): string {
  return questionText(useAppLocaleStore.getState().locale, key, vars);
}

export function useQuestionText() {
  const locale = useAppLocaleStore((state) => state.locale);
  const qt = useCallback(
    (key: QuestionTextKey, vars?: Record<string, string | number>) => questionText(locale, key, vars),
    [locale]
  );
  return useMemo(() => ({ locale, qt }), [locale, qt]);
}
