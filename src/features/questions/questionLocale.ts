export const QUESTION_TRANSLATIONS: Record<AppLocale, Dictionary> = { tr, en, es, fr, pt, ru, ar, hi, zh };

export function questionText(
  locale: AppLocale,
  key: QuestionTextKey,
  vars?: Record<string, string | number>
): string {
  let value = QUESTION_TRANSLATIONS[locale]?.[key] || tr[key];
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
  }
  return value;
}

