export const QUESTION_TRANSLATIONS: Record<AppLocale, Dictionary> = { tr, en, es, fr, pt, ru, ar, hi, zh };

export function questionText(
  locale: AppLocale,
  key: QuestionTextKey,
  vars?: Record<string, string | number>
): string {
  let value = QUESTION_TRANSLATIONS[locale]?.[key] || tr[key];
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
  }
  return value;
}

const CATEGORY_KEYS: Record<string, QuestionTextKey> = {
  food: 'catFood',
  fun: 'catFun',
  lifestyle: 'catLifestyle',
  music: 'catMusic',
  personality: 'catPersonality',
  relationships: 'catRelationships',
  social: 'catSocial',
  travel: 'catTravel',
  weekend: 'catWeekend',
};

export function questionCategoryKey(category: string): QuestionTextKey | null {
  return CATEGORY_KEYS[String(category || '').toLowerCase()] || null;
}

