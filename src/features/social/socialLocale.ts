export const SOCIAL_TRANSLATIONS: Record<AppLocale, Dictionary> = { tr, en, es, fr, pt, ru, ar, hi, zh };

export function socialText(
  locale: AppLocale,
  key: SocialTextKey,
  vars?: Record<string, string | number>
): string {
  let value = SOCIAL_TRANSLATIONS[locale]?.[key] || tr[key];
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
  }
  return value;
}

export function useSocialText() {
  const locale = useAppLocaleStore((state) => state.locale);
  const st = useCallback(
    (key: SocialTextKey, vars?: Record<string, string | number>) => socialText(locale, key, vars),
    [locale]
  );
  return useMemo(() => ({ locale, st }), [locale, st]);
}
