export const APP_LOCALE_LABELS: Record<AppLocale, string> = {
  tr: 'Türkçe', en: 'English', es: 'Español', fr: 'Français', pt: 'Português',
  ru: 'Русский', ar: 'العربية', hi: 'हिन्दी', zh: '中文',
};

export function matchSupportedLocale(value?: string | null): AppLocale | null {
  const code = value?.trim().toLowerCase().replace('_', '-').split('-')[0] as AppLocale | undefined;
  return code && SUPPORTED_APP_LOCALES.includes(code) ? code : null;
}

interface InitialLocaleState {
  locale: AppLocale;
  needsLanguageSelection: boolean;
}

export function resolveInitialLocale(
  persistedLocale?: string | null,
  deviceLocale?: string | null,
): InitialLocaleState {
  const persisted = matchSupportedLocale(persistedLocale);
  if (persisted) return { locale: persisted, needsLanguageSelection: false };

  const device = matchSupportedLocale(deviceLocale);
  if (device) return { locale: device, needsLanguageSelection: false };

  return { locale: UNSUPPORTED_DEVICE_FALLBACK_LOCALE, needsLanguageSelection: true };
}

function readPersistedLocale(): string | null {
  if (typeof window === 'undefined') return null;
  try {
    return window.localStorage.getItem(APP_LOCALE_STORAGE_KEY);
  } catch {
    return null;
  }
}

function persistLocale(locale: AppLocale) {
  if (typeof window === 'undefined') return;
  try {
    window.localStorage.setItem(APP_LOCALE_STORAGE_KEY, locale);
  } catch {
    // A storage failure must not prevent an in-session language change.
  }
}

function initialLocaleState(): InitialLocaleState {
  if (typeof window === 'undefined') {
    return { locale: PRODUCT_DEFAULT_LOCALE, needsLanguageSelection: false };
  }
  return resolveInitialLocale(readPersistedLocale(), window.navigator.language);
}

function applyDocumentLocale(locale: AppLocale) {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = locale;
  document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr';
}

interface AppLocaleState {
  locale: AppLocale;
  needsLanguageSelection: boolean;
  setLocale: (locale: AppLocale) => void;
}

const startingState = initialLocaleState();
applyDocumentLocale(startingState.locale);

export const useAppLocaleStore = create<AppLocaleState>((set) => ({
  ...startingState,
  setLocale: (locale) => {
    persistLocale(locale);
    applyDocumentLocale(locale);
    set({ locale, needsLanguageSelection: false });
  },
}));

export function useAppTranslation() {
  const locale = useAppLocaleStore((state) => state.locale);
  return {
    locale,
    t: (key: AppMessageKey) => messages[locale][key] || tr[key],
  };
}

/** Non-hook equivalent of `useAppTranslation().t` for class components (e.g. ErrorBoundary,
 * which can't call hooks) and other non-React call sites. Reads the current locale once at
 * call time rather than subscribing, which is fine for one-shot renders like a crash screen. */
export function translateSync(key: AppMessageKey): string {
  const locale = useAppLocaleStore.getState().locale;
  return messages[locale][key] || tr[key];
}

export function getMissingAppTranslationKeys(): Record<AppLocale, AppMessageKey[]> {
  const keys = Object.keys(tr) as AppMessageKey[];
  return Object.fromEntries(
    SUPPORTED_APP_LOCALES.map((locale) => [locale, keys.filter((key) => !messages[locale][key])])
  ) as Record<AppLocale, AppMessageKey[]>;
}
